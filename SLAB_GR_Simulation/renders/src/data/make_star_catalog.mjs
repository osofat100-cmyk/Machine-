// Generator for stars_mag5.js (run once; the output is committed).
//   npm install d3-celestial   (into any scratch directory; version used: 0.7.35)
//   node renders/src/data/make_star_catalog.mjs <path to node_modules/d3-celestial/data/stars.6.json> [magLimit=5.0]
// Source file: d3-celestial data/stars.6.json (GeoJSON, J2000; longitude = RA in degrees mapped to -180..180,
// latitude = Dec; properties mag = apparent magnitude, bv = B-V colour index; feature id = Hipparcos number).
// d3-celestial (c) 2015 Olaf Frohn, BSD-3-Clause; its readme names the star source as
// "XHIP: An Extended Hipparcos Compilation; Anderson E., Francis C. (2012), VizieR V/137D".
import fs from 'node:fs';
import path from 'node:path';
const src = process.argv[2];
const magLimit = parseFloat(process.argv[3] ?? '5.0');
const gj = JSON.parse(fs.readFileSync(src, 'utf8'));
const rows = [];
for (const ft of gj.features) {
  const m = +ft.properties.mag; if (!(m <= magLimit)) continue;
  let [lon, lat] = ft.geometry.coordinates; const ra = (lon + 360) % 360;
  const bv = parseFloat(ft.properties.bv);
  rows.push([ft.id, +ra.toFixed(4), +lat.toFixed(4), +m.toFixed(2), isFinite(bv) ? +bv.toFixed(3) : null]);
}
rows.sort((a, b) => a[3] - b[3]);
const out = `// GENERATED by renders/src/data/make_star_catalog.mjs — do not edit by hand.
// ${rows.length} stars with V <= ${magLimit} from d3-celestial ${'0.7.35'} data/stars.6.json.
// Attribution: d3-celestial, Copyright (c) 2015 Olaf Frohn, BSD-3-Clause licence (https://github.com/ofrohn/d3-celestial).
// Star data source as stated in the d3-celestial readme: XHIP: An Extended Hipparcos Compilation;
// Anderson E., Francis C. (2012) [VizieR V/137D] (Astronomy Letters 38, 331; arXiv:1108.4971).
// NOTE: the upgrade brief assumed the HYG database; the package's own readme names XHIP, not HYG.
// Licence of the underlying catalogue beyond the package's BSD release: INSUFFICIENT DATA TO VERIFY
// (the package ships it under its BSD licence; CDS/VizieR usage conventions ask for acknowledgement).
// Columns: HIP number, RA [deg, J2000], Dec [deg, J2000], V magnitude, B-V colour index (null if absent).
export const STAR_COLUMNS = ['hip', 'ra_deg', 'dec_deg', 'vmag', 'bv'];
export const STARS = ${JSON.stringify(rows).replace(/\],\[/g, '],\n[')};
`;
fs.writeFileSync(path.join(path.dirname(new URL(import.meta.url).pathname), 'stars_mag5.js'), out);
console.log(`wrote ${rows.length} stars`);
